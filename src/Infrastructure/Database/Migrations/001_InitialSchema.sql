BEGIN;

-- Schemas
CREATE SCHEMA IF NOT EXISTS roles;
CREATE SCHEMA IF NOT EXISTS org;
CREATE SCHEMA IF NOT EXISTS risk;
CREATE SCHEMA IF NOT EXISTS assessment;
CREATE SCHEMA IF NOT EXISTS treatment;
CREATE SCHEMA IF NOT EXISTS import_data;
CREATE SCHEMA IF NOT EXISTS report;

-- DB-1: Roles and access
CREATE TABLE roles.roles (
    role_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code text NOT NULL UNIQUE CHECK (role_code IN
        ('ADMIN','CEO','RESK_SPECIALIST','DIRECTOR','OWNER','EMPLOYEE')),
    role_name varchar(200) NOT NULL,
    is_role_active boolean NOT NULL DEFAULT true
);
CREATE TABLE roles.rights (
    right_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    right_code varchar(150) NOT NULL UNIQUE,
    right_description text NOT NULL
);
CREATE TABLE roles.users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_fio varchar(250) NOT NULL,
    user_email varchar(320) NOT NULL UNIQUE,
    user_password_hash text NOT NULL,
    is_user_active boolean NOT NULL DEFAULT true
);
CREATE TABLE roles.user_roles (
    user_role_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES roles.users(user_id),
    role_id integer NOT NULL REFERENCES roles.roles(role_id),
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE(user_id, role_id)
);
CREATE TABLE roles.role_rights (
    role_right_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id integer NOT NULL REFERENCES roles.roles(role_id),
    right_id integer NOT NULL REFERENCES roles.rights(right_id),
    UNIQUE(role_id, right_id)
);

-- DB-2: Organization
CREATE TABLE org.directorates (
    directorate_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    directorate_title varchar(250) NOT NULL,
    is_directorate_active boolean NOT NULL DEFAULT true
);
CREATE TABLE org.persons (
    person_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NULL REFERENCES roles.users(user_id),
    directorate_id integer NULL REFERENCES org.directorates(directorate_id),
    person_position varchar(250),
    is_person_active boolean NOT NULL DEFAULT true
);
CREATE TABLE org.processes (
    process_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    directorate_id integer NOT NULL REFERENCES org.directorates(directorate_id),
    process_title varchar(250) NOT NULL,
    owner_id integer NOT NULL REFERENCES org.persons(person_id),
    process_description text,
    is_process_active boolean NOT NULL DEFAULT true
);
CREATE TABLE org.assets (
    asset_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_title varchar(250) NOT NULL,
    asset_inventory_num varchar(120) UNIQUE,
    asset_hour_cost numeric(18,2) NOT NULL CHECK(asset_hour_cost >= 0),
    is_asset_active boolean NOT NULL DEFAULT true
);
CREATE TABLE org.responsibility (
    responsibility_type_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id integer NOT NULL REFERENCES org.persons(person_id),
    directed_id integer NULL REFERENCES org.persons(person_id),
    responsibility_type varchar(80) NOT NULL,
    is_responsibility_active boolean NOT NULL DEFAULT true
);

-- DB-3: Risk reference data
CREATE TABLE risk.hazard_groups (
    hazard_group_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hazard_group_name varchar(250) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE risk.hazards (
    hazard_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hazard_group_id integer NOT NULL REFERENCES risk.hazard_groups(hazard_group_id),
    hazard_name varchar(250) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE(hazard_group_id, hazard_name)
);
CREATE TABLE risk.categories (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name varchar(250) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

-- DB-4: Risks
CREATE TABLE risk.risks (
    risk_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_title varchar(300) NOT NULL,
    risk_description text NOT NULL,
    hazard_id integer NOT NULL REFERENCES risk.hazards(hazard_id),
    category_id integer NOT NULL REFERENCES risk.categories(category_id),
    risk_author_id integer NOT NULL REFERENCES roles.users(user_id),
    asset_id integer NULL REFERENCES org.assets(asset_id),
    risk_status varchar(50) NOT NULL,
    risk_acceptance_level varchar(50),
    risk_close_reason text
);
CREATE TABLE risk.risk_processes (
    risk_process_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_id integer NOT NULL REFERENCES risk.risks(risk_id),
    risk_processed_owner_id integer NOT NULL REFERENCES roles.users(user_id),
    person_id integer NOT NULL REFERENCES org.persons(person_id),
    is_risk_process_primary boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX uq_risk_process_primary
    ON risk.risk_processes(risk_id) WHERE is_risk_process_primary;
CREATE TABLE risk.comments (
    comment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_author_id integer NOT NULL REFERENCES roles.users(user_id),
    comment_text text NOT NULL,
    comment_entity_type varchar(50) NOT NULL,
    comment_entity_id integer NOT NULL,
    is_comment_active boolean NOT NULL DEFAULT true,
    comment_created timestamptz NOT NULL DEFAULT now(),
    comment_updated timestamptz NOT NULL DEFAULT now()
);

-- DB-5: Assessment
CREATE TABLE assessment.methods (
    method_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_title varchar(250) NOT NULL UNIQUE,
    method_description text
);
CREATE TABLE assessment.likelihood_levels (
    likelihood_level_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_id integer NOT NULL REFERENCES assessment.methods(method_id),
    likelihood_level_name varchar(200) NOT NULL,
    likelihood_level_weight integer NOT NULL CHECK(likelihood_level_weight >= 0),
    UNIQUE(method_id, likelihood_level_name),
    UNIQUE(method_id, likelihood_level_weight)
);
CREATE TABLE assessment.impact_levels (
    impact_level_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_id integer NOT NULL REFERENCES assessment.methods(method_id),
    impact_level_name varchar(200) NOT NULL,
    impact_level_weight integer NOT NULL CHECK(impact_level_weight >= 0),
    impact_level_loss numeric(18,2) NOT NULL CHECK(impact_level_loss >= 0),
    impact_level_max numeric(18,2) NOT NULL CHECK(impact_level_max >= impact_level_loss),
    UNIQUE(method_id, impact_level_name),
    UNIQUE(method_id, impact_level_weight)
);
CREATE TABLE assessment.assessments (
    assessment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_id integer NOT NULL REFERENCES risk.risks(risk_id),
    method_id integer NOT NULL REFERENCES assessment.methods(method_id),
    likelihood_level_id integer NOT NULL REFERENCES assessment.likelihood_levels(likelihood_level_id),
    impact_level_id integer NOT NULL REFERENCES assessment.impact_levels(impact_level_id),
    loss_amount numeric(18,2) NOT NULL CHECK(loss_amount >= 0),
    downtime_weeks numeric(10,2),
    downtime_days numeric(10,2),
    downtime_hours numeric(10,2),
    downtime_total_hours numeric(10,2),
    hourly_downtime_cost numeric(18,2),
    risk_score integer NOT NULL CHECK(risk_score >= 0),
    response_mode varchar(50),
    is_active boolean NOT NULL DEFAULT true,
    created_by_id integer NOT NULL REFERENCES roles.users(user_id),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_assessments_risk_created ON assessment.assessments(risk_id, created_at DESC);
CREATE UNIQUE INDEX uq_assessment_active_per_risk ON assessment.assessments(risk_id) WHERE is_active;
CREATE TABLE assessment.risk_acceptance_settings (
    setting_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_id integer NOT NULL UNIQUE REFERENCES assessment.methods(method_id),
    owner_max_score integer NOT NULL,
    director_max_score integer NOT NULL,
    ceo_max_score integer NOT NULL
);

-- DB-6: Treatment
CREATE TABLE treatment.treatments (
    treatment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_process_id integer NOT NULL REFERENCES risk.risk_processes(risk_process_id),
    treatment_title varchar(300) NOT NULL,
    treatment_description text,
    treatment_status varchar(50) NOT NULL,
    treatment_date timestamptz NOT NULL,
    treatment_cost_plan numeric(18,2) NOT NULL CHECK(treatment_cost_plan >= 0),
    treatment_cost_act numeric(18,2) NOT NULL CHECK(treatment_cost_act >= 0),
    treatment_created_by_id integer NOT NULL REFERENCES roles.users(user_id),
    treatment_assigned_id integer NULL REFERENCES roles.users(user_id),
    treatment_created timestamptz NOT NULL DEFAULT now(),
    treatment_updated timestamptz
);
-- approval_date and approval_by_id are nullable until the request is decided.
CREATE TABLE treatment.approval_requests (
    approval_request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    treatment_id integer NOT NULL REFERENCES treatment.treatments(treatment_id),
    approval_required_level varchar(50) NOT NULL,
    approval_request_status varchar(50) NOT NULL,
    approval_created_by_id integer NOT NULL REFERENCES roles.users(user_id),
    approval_created timestamptz NOT NULL DEFAULT now(),
    approval_comment text,
    approval_date timestamptz,
    approval_reason text,
    approval_by_id integer REFERENCES roles.users(user_id)
);
CREATE TABLE treatment.treatment_approval_settings (
    treatment_approval_set_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_threshold integer NOT NULL,
    director_threshold integer NOT NULL,
    ceo_threshold integer NOT NULL
);

-- DB-7: Import
CREATE TABLE import_data.file_upload (
    file_upload_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_upload_title varchar(300) NOT NULL,
    file_upload_status varchar(50) NOT NULL,
    file_upload_person_id integer NOT NULL REFERENCES org.persons(person_id),
    file_upload_rows integer NOT NULL DEFAULT 0 CHECK(file_upload_rows >= 0),
    file_upload_rows_valid integer NOT NULL DEFAULT 0 CHECK(file_upload_rows_valid >= 0),
    file_upload_rows_invalid integer NOT NULL DEFAULT 0 CHECK(file_upload_rows_invalid >= 0),
    file_upload_report text NOT NULL DEFAULT '',
    file_upload_error text
);

-- DB-8: Reports
CREATE TABLE report.report_templates (
    template_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_title varchar(250) NOT NULL,
    is_template_active boolean NOT NULL DEFAULT true
);
CREATE TABLE report.reports (
    report_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id integer NOT NULL REFERENCES report.report_templates(template_id),
    report_title varchar(300) NOT NULL,
    report_status varchar(50) NOT NULL,
    report_format varchar(30) NOT NULL,
    report_path text NOT NULL,
    report_generated_by_id integer NOT NULL REFERENCES roles.users(user_id),
    report_generated_at timestamptz NOT NULL DEFAULT now()
);

-- Indexes
CREATE INDEX ix_user_roles_user_id ON roles.user_roles(user_id);
CREATE INDEX ix_role_rights_role_id ON roles.role_rights(role_id);
CREATE INDEX ix_persons_user ON org.persons(user_id);
CREATE INDEX ix_processes_directorate ON org.processes(directorate_id);
CREATE INDEX ix_risks_hazard ON risk.risks(hazard_id);
CREATE INDEX ix_risks_category ON risk.risks(category_id);
CREATE INDEX ix_risks_author ON risk.risks(risk_author_id);
CREATE INDEX ix_risk_processes_person ON risk.risk_processes(person_id);
CREATE INDEX ix_treatments_assignee ON treatment.treatments(treatment_assigned_id);
CREATE INDEX ix_comments_entity ON risk.comments(comment_entity_type, comment_entity_id, comment_created);

-- Seed roles. Users and user-role assignments are intentionally not seeded.
INSERT INTO roles.roles(role_code, role_name) VALUES
    ('ADMIN', 'Администратор'),
    ('CEO', 'Генеральный директор'),
    ('RISK_SPECIALIST', 'Специалист по рискам'),
    ('DIRECTOR', 'Директор'),
    ('OWNER', 'Владелец риска'),
    ('EMPLOYEE', 'Сотрудник')
ON CONFLICT(role_code) DO NOTHING;

-- Seed rights from the provided access matrix.
INSERT INTO roles.rights(right_code, right_description) VALUES
    ('view_risk', 'Просмотр рисков'),
    ('comment_components', 'Комментирование риска или меры'),
    ('create_components', 'Создание риска или меры'),
    ('edit_components', 'Редактирование риска или меры'),
    ('split_risk', 'Разделение риска на процессы'),
    ('transfer_risk', 'Передача риска в другой процесс'),
    ('assess_risk', 'Оценка и переоценка риска'),
    ('accept_risk', 'Принятие риска'),
    ('approve_treatment', 'Согласование меры'),
    ('assign_treatment_executor', 'Назначение ответственного'),
    ('close_risk', 'Закрытие риска'),
    ('execute_treatment', 'Выполнение меры'),
    ('work_report', 'Просмотр и экспорт отчётов'),
    ('import_data', 'Импорт данных')
ON CONFLICT(right_code) DO NOTHING;

-- Role-right matrix. Missing pairs mean no permission.
WITH grants(role_code, right_code) AS (
    VALUES
    ('ADMIN','view_risk'), ('CEO','view_risk'), ('RESK_SPECIALIST','view_risk'),
    ('DIRECTOR','view_risk'), ('OWNER','view_risk'), ('EMPLOYEE','view_risk'),
    ('ADMIN','comment_components'), ('CEO','comment_components'),
    ('RESK_SPECIALIST','comment_components'), ('DIRECTOR','comment_components'),
    ('OWNER','comment_components'), ('EMPLOYEE','comment_components'),
    ('ADMIN','create_components'), ('OWNER','create_components'), ('EMPLOYEE','create_components'),
    ('ADMIN','edit_components'), ('OWNER','edit_components'),
    ('ADMIN','split_risk'), ('OWNER','split_risk'),
    ('ADMIN','transfer_risk'), ('OWNER','transfer_risk'),
    ('ADMIN','assess_risk'), ('OWNER','assess_risk'),
    ('ADMIN','accept_risk'), ('CEO','accept_risk'), ('RESK_SPECIALIST','accept_risk'),
    ('DIRECTOR','accept_risk'), ('OWNER','accept_risk'),
    ('ADMIN','approve_treatment'), ('CEO','approve_treatment'),
    ('RESK_SPECIALIST','approve_treatment'), ('DIRECTOR','approve_treatment'),
    ('OWNER','approve_treatment'),
    ('ADMIN','assign_treatment_executor'), ('OWNER','assign_treatment_executor'),
    ('ADMIN','close_risk'), ('OWNER','close_risk'),
    ('ADMIN','execute_treatment'), ('OWNER','execute_treatment'), ('EMPLOYEE','execute_treatment'),
    ('ADMIN','work_report'), ('CEO','work_report'), ('RESK_SPECIALIST','work_report'),
    ('DIRECTOR','work_report'), ('OWNER','work_report'),
    ('ADMIN','import_data')
)
INSERT INTO roles.role_rights(role_id, right_id)
SELECT r.role_id, p.right_id
FROM grants g
JOIN roles.roles r ON r.role_code = g.role_code
JOIN roles.rights p ON p.right_code = g.right_code
ON CONFLICT(role_id, right_id) DO NOTHING;

COMMIT;
